// Packages the Linux build (release/v<version>-linux/linux-unpacked, from `electron-builder --linux dir`) for
// Arch Linux, from any OS: a pacman package (bidmail-<version>-1-x86_64.pkg.tar.zst, `sudo pacman -U`) and a
// portable .tar.gz, both with Linux permissions. bsdtar (Windows' built-in tar, or libarchive) builds the
// archives from mtree specs, so file modes, root ownership and the /usr/bin symlink are right without Linux.
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const version = pkg.version
const outDir = path.join(root, 'release', `v${version}-linux`)
const app = path.join(outDir, 'linux-unpacked')
if (!fs.existsSync(path.join(app, 'bidmail'))) throw new Error(`Build the Linux app first: npx electron-builder --linux dir --x64 --config.directories.output=release/v${version}-linux`)

const stage = fs.mkdtempSync(path.join(os.tmpdir(), 'bidmail-arch-'))
const now = Math.floor(Date.now() / 1000)
const fwd = (p) => p.replace(/\\/g, '/')
const esc = (p) => p.replace(/[^A-Za-z0-9._\-/+@:]/g, (c) => '\\' + c.charCodeAt(0).toString(8).padStart(3, '0'))
const isElf = (f) => {
  const b = Buffer.alloc(4)
  const fd = fs.openSync(f, 'r')
  fs.readSync(fd, b, 0, 4, 0)
  fs.closeSync(fd)
  return b.toString('latin1') === '\x7fELF'
}

// The app's files under /opt/bidmail, with Linux modes: programs and libraries 755, chrome-sandbox setuid 4755.
const entries = [] // { path, type, mode, contents?, link?, size? }
const dirs = new Set()
const addDir = (p) => {
  for (let d = path.posix.dirname(p); d !== '.' && !dirs.has(d); d = path.posix.dirname(d)) dirs.add(d)
}
const addFile = (p, src, mode) => {
  addDir(p)
  entries.push({ path: p, type: 'file', mode, contents: fwd(src), size: fs.statSync(src).size })
}
const walk = (dir, rel) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const src = path.join(dir, e.name)
    const r = rel ? `${rel}/${e.name}` : e.name
    if (e.isDirectory()) walk(src, r)
    else addFile(`opt/bidmail/${r}`, src, r === 'chrome-sandbox' ? '4755' : isElf(src) ? '0755' : '0644')
  }
}
walk(app, '')

// Menu entry and icon.
const desktop = path.join(stage, 'bidmail.desktop')
fs.writeFileSync(desktop, [
  '[Desktop Entry]',
  'Name=BidMail',
  'GenericName=Email & Bid Tracking',
  'Comment=Email and bid tracking for construction estimators',
  'Exec=/usr/bin/bidmail %U',
  'Icon=bidmail',
  'Terminal=false',
  'Type=Application',
  'StartupWMClass=BidMail',
  'Categories=Office;Network;Email;',
  ''
].join('\n'))
addFile('usr/share/applications/bidmail.desktop', desktop, '0644')
const icon = path.join(root, 'build', 'icon.png')
const px = fs.readFileSync(icon).readUInt32BE(16)
addFile(`usr/share/icons/hicolor/${px}x${px}/apps/bidmail.png`, icon, '0644')
addDir('usr/bin/bidmail')
entries.push({ path: 'usr/bin/bidmail', type: 'link', mode: '0777', link: '/opt/bidmail/bidmail' })

// Paths without a leading ./ (as makepkg writes them): pacman looks for exactly ".PKGINFO".
const line = (prefix, e) =>
  `${esc(prefix + e.path)} type=${e.type} uid=0 gid=0 uname=root gname=root mode=${e.mode} time=${now}.0` +
  (e.contents ? ` contents=${esc(e.contents)}` : '') +
  (e.link ? ` link=${esc(e.link)}` : '')
const spec = (prefix, extra = []) =>
  ['#mtree', ...extra, ...[...dirs].sort().map((d) => line(prefix, { path: d, type: 'dir', mode: '0755' })), ...entries.map((e) => line(prefix, e))].join('\n') + '\n'
const bsdtar = (args) => execFileSync('tar', args, { stdio: ['ignore', 'pipe', 'inherit'], cwd: stage })

// .PKGINFO: what pacman shows and checks. Depends: what Electron's bundled Chromium needs on Arch.
const size = entries.reduce((a, e) => a + (e.size ?? 0), 0)
const depends = ['gtk3', 'nss', 'alsa-lib', 'libxss', 'libxtst', 'libxkbcommon', 'libxcomposite', 'libxdamage', 'libxrandr', 'mesa', 'libdrm', 'at-spi2-core', 'libcups', 'expat', 'dbus', 'xdg-utils']
fs.writeFileSync(path.join(stage, '.PKGINFO'), [
  `# Generated by BidMail scripts/package-arch.mjs`,
  `pkgname = bidmail`,
  `pkgbase = bidmail`,
  `xdata = pkgtype=pkg`,
  `pkgver = ${version}-1`,
  `pkgdesc = ${pkg.description}`,
  `builddate = ${now}`,
  `packager = 5310S`,
  `size = ${size}`,
  `arch = x86_64`,
  `license = LicenseRef-BidMail`,
  ...depends.map((d) => `depend = ${d}`),
  `optdepend = libsecret: keep sign-ins in the system keyring (GNOME Keyring, KWallet)`,
  ''
].join('\n'))
const meta = (name) => `${name} type=file uid=0 gid=0 uname=root gname=root mode=0644 time=${now}.0 contents=${esc(fwd(path.join(stage, name)))}`

// .MTREE (what makepkg adds, for `pacman -Qkk`): made from the package's own entries.
fs.writeFileSync(path.join(stage, 'payload.mtree'), spec('', [meta('.PKGINFO')]))
bsdtar(['-cf', 'payload.tar', '@payload.mtree'])
bsdtar(['-czf', '.MTREE', '--format=mtree', '--options=!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link', '@payload.tar'])

// The pacman package: .PKGINFO and .MTREE first, then the files.
const pkgFile = path.join(outDir, `bidmail-${version}-1-x86_64.pkg.tar.zst`)
fs.writeFileSync(path.join(stage, 'pkg.mtree'), spec('', [meta('.PKGINFO'), meta('.MTREE')]))
bsdtar(['--zstd', '-cf', fwd(pkgFile), '@pkg.mtree'])

// A portable archive for any Linux: run bidmail-<version>/bidmail.
const tgz = path.join(outDir, `bidmail-${version}-linux-x64.tar.gz`)
const portable = entries.filter((e) => e.path.startsWith('opt/bidmail/')).map((e) => ({ ...e, path: e.path.replace('opt/bidmail/', '') }))
const pdirs = [...new Set(portable.flatMap((e) => { const out = []; for (let d = path.posix.dirname(e.path); d !== '.'; d = path.posix.dirname(d)) out.push(d); return out }))]
const prefix = `bidmail-${version}/`
fs.writeFileSync(path.join(stage, 'portable.mtree'), ['#mtree', `${prefix.slice(0, -1)} type=dir uid=0 gid=0 mode=0755 time=${now}.0`, ...pdirs.sort().map((d) => line(prefix, { path: d, type: 'dir', mode: '0755' })), ...portable.map((e) => line(prefix, e))].join('\n') + '\n')
bsdtar(['-czf', fwd(tgz), '@portable.mtree'])

fs.rmSync(stage, { recursive: true, force: true })
for (const f of [pkgFile, tgz]) console.log(`${path.relative(root, f)}  ${(fs.statSync(f).size / 1024 ** 2).toFixed(1)} MB`)